"""Documentation projection of the existing frog.examples.index, never semantics.

The canonical index and document/dependency bytes are read-only inputs. No
execution result is inferred here. The ownership manifest below only bounds
generated-file cleanup; it is not another example or operator registry.
"""
from __future__ import annotations

from dataclasses import dataclass
import hashlib
import html
import json
from pathlib import Path, PurePosixPath
import re
from urllib.parse import quote


MARKER = "<!-- Generated by tools/export_studio_help.py; example projection. -->"
OWNERSHIP = "assets/examples/.export-owned.json"
PROFILE_PAGE = "docs/reference/studio-draft-examples.md"
LIBRARY_NAMES = {"frog-example-native-library.dll"}
LIBRARY_SOURCE_NAMES = ("resources_structures.c", "resources_structures.h", "CMakeLists.txt", "README.md")
BACKENDS = {"native-fast", "native-debug", "simulation"}
MODES = {"execution", "expected-diagnostic", "expected-abort", "persistence", "interactive"}
COMPARATORS = {"exact", "float", "ieee-bits", "nan", "positive-infinity", "negative-infinity", "document_path", "studio_directory", "temporary_directory"}
SPECIAL_VALUES = {"nan", "positive-infinity", "negative-infinity"}
PRIVATE_PATH = re.compile(rb"(?:[a-z]:[\\/]+users[\\/]+|/users/|/home/|file://|github\.com/graiphic/frog-studio)", re.IGNORECASE)


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _pairs(pairs):
    out = {}
    for key, value in pairs:
        if key in out:
            raise ValueError(f"Duplicate JSON member: {key}")
        out[key] = value
    return out


def parse_json(data):
    def invalid(value):
        raise ValueError(f"Non-JSON numeric value: {value}")
    return json.loads(data, object_pairs_hook=_pairs, parse_constant=invalid)


def relative_name(name: str) -> str:
    if not isinstance(name, str) or not name or any(c in name for c in "\\:\0\r\n") or name.startswith("/"):
        raise ValueError(f"Unsafe example-relative path: {name!r}")
    parts = name.split("/")
    if any(not part or part in (".", "..") for part in parts):
        raise ValueError(f"Unsafe example-relative path: {name!r}")
    return name


def within(root: Path, name: str) -> Path:
    name = relative_name(name)
    root = root.resolve()
    path = (root / name).resolve()
    if path == root or not path.is_relative_to(root):
        raise ValueError(f"Example path escapes its root: {name}")
    return path


def owned_name(name: str) -> bool:
    relative_name(name)
    return name == PROFILE_PAGE or name.startswith(("docs/examples/", "assets/examples/"))


def destination(root: Path, name: str) -> Path:
    """Check final resolved output before writing or pruning, including symlinks."""
    result = within(root, name)
    if result != root.resolve() / relative_name(name):
        raise ValueError(f"Output path redirects through a link: {name}")
    return result


def plain(value) -> str:
    return html.escape(str(value), quote=False).replace("|", "\\|").replace("[", "\\[").replace("]", "\\]")


def inline(value) -> str:
    return "`" + str(value).replace("`", "'").replace("|", "\\|").replace("\n", " ") + "`"


def link(title: str, path: str) -> str:
    return f"[{plain(title)}]({quote(path, safe='/._-')})"


def download(title: str, path: str) -> str:
    # Raw HTML avoids Docsify's Markdown router. Its existing asset rewrite
    # resolves this same relative link under a GitHub Pages subdirectory.
    return '<a href="' + html.escape(quote(path, safe="/._-"), quote=True) + '" download>' + html.escape(title) + "</a>"


def example_route(entry: dict) -> str:
    return "docs/examples/" + entry["id"] + ".md"


def _text(row: dict, field: str) -> str:
    value = row.get(field)
    if not isinstance(value, str) or not value.strip():
        raise ValueError(f"Example {row.get('id', '?')} needs {field}")
    return value


def _strings(row: dict, field: str, required=False) -> list[str]:
    values = row.get(field, [])
    if not isinstance(values, list) or any(not isinstance(v, str) or not v for v in values) or len(set(values)) != len(values) or (required and not values):
        raise ValueError(f"Example {row.get('id', '?')} has invalid {field}")
    return values


@dataclass
class ExampleProjection:
    entries: list[dict]
    files: dict[str, bytes]
    by_catalog: dict[str, list[dict]]
    revisions: list[int]


def load_examples(index: Path, catalog: dict) -> ExampleProjection:
    if not index.is_file():
        raise ValueError("Canonical example index is missing; generate the real FROG/Examples/index.v1.json before exporting documentation.")
    raw_index = index.read_bytes()
    if PRIVATE_PATH.search(raw_index):
        raise ValueError("Canonical example index contains a private URL or personal absolute path")
    if len(raw_index) > 16 * 1024 * 1024:
        raise ValueError("Example index exceeds its existing 16 MiB reader limit")
    root = index.parent.resolve()
    data = parse_json(raw_index.decode("utf-8-sig"))
    if not isinstance(data, dict) or data.get("schema") != "frog.examples.index" or type(data.get("version")) is not int or data["version"] != 1 or not isinstance(data.get("examples"), list) or not data["examples"]:
        raise ValueError("Canonical example index has an invalid or empty version-1 envelope")
    files = {"assets/examples/index.v1.json": raw_index}
    entries, ids, paths, revisions = [], set(), set(), set()
    by_catalog = {cid: [] for cid in catalog}
    identities = {}
    library_dirs = set()

    def copy(name, document=False):
        name = relative_name(name)
        source = within(root, name)
        if not source.is_file():
            raise ValueError(f"Declared example file is missing: {name}")
        old = identities.setdefault(source, name)
        if old != name:
            raise ValueError(f"Two example paths alias the same file: {old}, {name}")
        target = "assets/examples/" + name
        value = source.read_bytes()
        if PRIVATE_PATH.search(value):
            raise ValueError(f"Example resource contains a private URL or personal absolute path: {name}")
        if target in files and files[target] != value:
            raise ValueError(f"Example file identity changed during export: {name}")
        files[target] = value
        if document:
            actual = parse_json(value.decode("utf-8-sig"))
            if not isinstance(actual, dict):
                raise ValueError(f"Example is not an actual document: {name}")
            return actual

    for row in data["examples"]:
        if not isinstance(row, dict):
            raise ValueError("Example index entries must be objects")
        eid = _text(row, "id")
        if len(eid) > 192 or eid in (".", "..") or not re.fullmatch(r"[A-Za-z0-9._-]+", eid) or eid.casefold() in ids:
            raise ValueError(f"Duplicate or unsafe example ID: {eid}")
        ids.add(eid.casefold())
        for field in ("title", "summary", "description", "family"):
            _text(row, field)
        profile, mode = _text(row, "profile"), _text(row, "mode")
        if profile not in ("studio-draft", "source-0.1") or mode not in MODES:
            raise ValueError(f"Unknown document profile or example mode: {eid}")
        objects = _strings(row, "catalog_ids", True)
        if any(cid not in catalog for cid in objects):
            raise ValueError(f"Example names an unknown catalog object: {eid}")
        backends = _strings(row, "backends")
        if any(backend not in BACKENDS for backend in backends):
            raise ValueError(f"Example names an unknown backend: {eid}")
        _strings(row, "tags")
        dependencies = _strings(row, "dependencies")
        path = relative_name(_text(row, "path"))
        if not path.endswith(".frog") or path.casefold() in paths:
            raise ValueError(f"Duplicate or non-FROG example path: {eid}")
        paths.add(path.casefold())
        actual = copy(path, True)
        if profile == "studio-draft":
            if actual.get("format") != "frog.document.draft" or "spec_version" in actual or type(actual.get("draft_revision")) is not int or actual["draft_revision"] < 0:
                raise ValueError(f"Studio Draft profile disagrees with actual document bytes: {eid}")
            revisions.add(actual["draft_revision"])
        elif actual.get("spec_version") != "0.1" or "format" in actual:
            raise ValueError(f"Public Source profile disagrees with actual document bytes: {eid}")
        for dependency in dependencies:
            dependency = relative_name(dependency)
            base = PurePosixPath(dependency).name
            if dependency.endswith(".frog"):
                copy(dependency, True)
            elif base in LIBRARY_NAMES and dependency == "Native/lib/" + base:
                copy(dependency)
                library_dirs.add(str(PurePosixPath(dependency).parent))
            else:
                raise ValueError(f"Dependency redistribution has not been reviewed: {dependency}")
        expected = row.get("expected")
        if not isinstance(expected, list) or (mode == "execution" and (not expected or not backends)):
            raise ValueError(f"Execution example needs its explicit typed oracle and backend: {eid}")
        if mode == "expected-diagnostic":
            _text(row, "expected_diagnostic")
        for value in expected:
            if not isinstance(value, dict) or value.get("comparator") not in COMPARATORS:
                raise ValueError(f"Invalid example comparator: {eid}")
            for field in ("widget_id", "type"):
                _text(value, field)
            if not isinstance(value.get("value_json"), str):
                raise ValueError(f"Expected value must retain its JSON lexeme string: {eid}")
            if value["comparator"] not in SPECIAL_VALUES:
                parse_json(value["value_json"])
            for field in ("absolute_tolerance", "relative_tolerance"):
                number = value.get(field)
                if isinstance(number, bool) or not isinstance(number, (float, int)) or not 0 <= number < float("inf"):
                    raise ValueError(f"Invalid expected tolerance: {eid}")
            if value.get("type_schema_json"):
                parse_json(value["type_schema_json"])
        if type(row.get("order", 0)) is not int or row.get("order", 0) < 0:
            raise ValueError(f"Invalid pedagogical order: {eid}")
        entries.append(row)
        for cid in objects:
            by_catalog[cid].append(row)

    # The canonical corpus lives in the public FROG repository. Keep that
    # repository's license with the exact redistributed files, not a guessed
    # license from the private application checkout.
    license_file = within(root.parent, "LICENSE")
    if not license_file.is_file():
        raise ValueError("The canonical corpus repository license is missing")
    files["assets/examples/LICENSE"] = license_file.read_bytes()
    notice_file = within(root.parent, "NOTICE")
    if notice_file.is_file():
        files["assets/examples/NOTICE"] = notice_file.read_bytes()
    for directory in sorted(library_dirs):
        for name in LIBRARY_SOURCE_NAMES:
            copy(directory + "/" + name)
    entries.sort(key=lambda e: (e.get("order", 0), e["id"]))
    for values in by_catalog.values():
        values.sort(key=lambda e: (e.get("order", 0), e["id"]))
    return ExampleProjection(entries, files, by_catalog, sorted(revisions))


def function_examples(projection: ExampleProjection, cid: str) -> list[str]:
    lines = ["## Examples", ""]
    examples = projection.by_catalog.get(cid, [])
    if not examples:
        return lines + ["No example for this object is currently declared in the shared index. " + link("Browse the available examples", "docs/examples/index.md") + ".", ""]
    lines += ["These are real `.frog` documents from the same index used by Studio. Backend names and expected results describe the examples; they are not execution certificates.", ""]
    for entry in examples:
        lines += ["- " + link(entry["title"], example_route(entry)) + " — " + plain(entry["summary"]) + " (" + inline(entry["mode"]) + ", " + inline(entry["profile"]) + ")."]
    return lines + [""]


def expected_display(value: dict) -> str:
    return {"document_path": "<current example document path>", "studio_directory": "<Studio installation directory>", "temporary_directory": "<system temporary directory>", "nan": "NaN", "positive-infinity": "+Inf", "negative-infinity": "-Inf"}.get(value["comparator"], value["value_json"])


def render_examples(projection: ExampleProjection, catalog: dict) -> dict[str, bytes]:
    artifacts = dict(projection.files)
    overview = [MARKER, "# Examples", "", "Open an actual `.frog` document, inspect its graph and compare its output with an independently declared expectation. These files use the same canonical index as Studio's Find Examples browser.", "", link("Document profiles and execution scope", PROFILE_PAGE) + " · " + download("Download the canonical index", "assets/examples/index.v1.json"), "", "The index declares intended results and required backends. Its presence does not establish a successful run, complete operator support or publication of a Studio Draft as public FROG Source.", ""]
    for family in sorted({entry["family"] for entry in projection.entries}):
        overview += ["## " + plain(family), ""]
        overview += ["- " + link(e["title"], example_route(e)) + " — " + plain(e["summary"]) for e in projection.entries if e["family"] == family]
        overview.append("")
    artifacts["docs/examples/index.md"] = "\n".join(overview).encode()
    for entry in projection.entries:
        lines = [MARKER, "# " + plain(entry["title"]), "", link("All examples", "docs/examples/index.md") + " · " + link("Document profile", PROFILE_PAGE), "", plain(entry["summary"]), "", "## What this example demonstrates", "", plain(entry["description"]), "", "## Open the actual document", "", download("Download " + PurePosixPath(entry["path"]).name, "assets/examples/" + entry["path"]), "", "Open the file in a Studio version admitting its format and its exact configured types. For dependent files, preserve the relative folder layout listed below. In the installed Studio browser, Open in Studio creates a working copy rather than editing the installed example.", "", "- Example ID: " + inline(entry["id"]) + ".", "- Document profile: " + inline(entry["profile"]) + ".", "- Mode: " + inline(entry["mode"]) + ".", "- Declared backends: " + (", ".join(inline(x) for x in entry["backends"]) or "none") + ".", "- Required capability: " + inline(entry.get("capability") or "not separately specified") + ".", "", "`native-fast` and `native-debug` request the product's native compiler/session path for this exact graph. `simulation` is an explicitly private oracle; it does not establish normal Studio Run support or supply a native fallback. Missing providers remain failures or unsupported cases, not successful outputs.", "", "## Expected result", ""]
        if entry["mode"] == "expected-diagnostic":
            lines += ["This is an intentional negative case. It must report exactly " + inline(entry["expected_diagnostic"]) + "; an unrelated refusal does not satisfy the expectation.", ""]
        elif entry["mode"] == "expected-abort":
            lines += ["This case requires its declared wait/Stop/restart interaction. The file or preview alone does not demonstrate cancellation.", ""]
        elif entry["mode"] in ("interactive", "persistence"):
            lines += ["This mode needs its stated interaction or persistence checks. It does not claim executable closure for every operation in the document.", ""]
        for value in entry["expected"]:
            lines += ["### " + plain(value["widget_id"]), "", "Type: " + inline(value["type"]) + "; comparison: " + inline(value["comparator"]) + ".", ""]
            expected = expected_display(value)
            fence = "`" * max(3, max((len(x) for x in re.findall(r"`+", expected)), default=0) + 1)
            lines += [fence + ("json" if value["comparator"] in ("exact", "float", "ieee-bits") else "text"), expected, fence, ""]
            if value["comparator"] == "float":
                lines += [f"Absolute tolerance: {inline(value['absolute_tolerance'])}; relative tolerance: {inline(value['relative_tolerance'])}.", ""]
        lines += ["These are expected values, not a report of executed tests. Integers retain their exact JSON lexemes; Array shapes and nominal types remain part of the example contract.", "", "## Related functions", ""]
        lines += ["- " + link(catalog[cid]["title_en"], catalog[cid]["route"]) + " " + inline(cid) for cid in entry["catalog_ids"]]
        lines += ["", "## Dependencies and redistribution", ""]
        if entry.get("dependencies"):
            lines += ["The paths below are relative to the canonical example-index directory. Download each file into the same relative path, not beside main.frog unless the path says so.", ""]
            lines += ["- " + inline(name) + " — " + download("Download", "assets/examples/" + name) for name in entry["dependencies"]]
        else:
            lines += ["No external file dependency is declared by this example."]
        for directory in sorted({str(PurePosixPath(name).parent) for name in entry.get("dependencies", []) if PurePosixPath(name).name in LIBRARY_NAMES}):
            lines += ["", "The bundled C teaching library is redistributable with its source, header and build recipe. Its portable source does not establish a Studio provider on another operating system.", ""]
            lines += ["- " + download(name, "assets/examples/" + directory + "/" + name) for name in LIBRARY_SOURCE_NAMES]
        lines += ["", download("Corpus repository license", "assets/examples/LICENSE") + ".", ""]
        artifacts[example_route(entry)] = "\n".join(lines).encode()
    revisions = ", ".join(str(n) for n in projection.revisions) or "none"
    artifacts[PROFILE_PAGE] = (MARKER + "\n# Studio Draft examples and execution scope\n\n" +
        "The extension `.frog` does not select one language authority. Each example declares its document profile in the shared index, and this export checks that declaration against the actual file bytes. It never renames keys or converts a file to another profile.\n\n" +
        "| Index profile | Actual envelope | Scope |\n| --- | --- | --- |\n| `studio-draft` | `format: \"frog.document.draft\"`, integer `draft_revision`, Studio `frontPanel` | Product authoring document; execution requires the actual admitted native provider |\n| `source-0.1` | `spec_version: \"0.1\"` | Public FROG Source with its existing validation, lowering and backend admission |\n\n" +
        "Draft revision, application version and public Source compatibility version are different identities. The copied Studio Draft files are not thereby published as public Source programs. Keeping the format unchanged is deliberate; successful execution of one graph does not admit all overloads of its functions.\n\n" +
        "Observed Studio Draft revisions in this index: " + inline(revisions) + ". This observation is not a new revision-admission rule.\n\n" +
        "The index and explanations describe expectations. This documentation export does not run Studio, test the ABI, or certify a backend. It does not publish a Git commit or deployment. NativeFast/NativeDebuggable, explicit private Simulation, persistence, interactive actions and expected failures retain their separate meanings.\n\n" +
        "Download files individually while retaining their index-relative paths. The only copied binary dependency reviewed by this exporter is the corpus's C sample library, accompanied by its own sources, header, build recipe and the corpus repository license. No private preparation archive, developer SDK or application binary is redistributed.\n\n" +
        link("Browse the actual examples", "docs/examples/index.md") + ".\n").encode()
    seal_example_ownership(artifacts)
    return artifacts


def seal_example_ownership(artifacts: dict[str, bytes]) -> None:
    records = [{"path": name, "sha256": sha256(data)} for name, data in sorted(artifacts.items()) if name != OWNERSHIP and owned_name(name)]
    manifest = {"schema": "graiphic.studio.example-export-files", "version": 1, "files": records}
    artifacts[OWNERSHIP] = (json.dumps(manifest, ensure_ascii=False, indent=2) + "\n").encode()


def stale_example_files(output: Path, artifacts: dict[str, bytes]) -> list[Path]:
    manifest_path = destination(output, OWNERSHIP)
    if not manifest_path.exists():
        return []
    manifest = parse_json(manifest_path.read_text(encoding="utf-8"))
    if manifest.get("schema") != "graiphic.studio.example-export-files" or manifest.get("version") != 1 or not isinstance(manifest.get("files"), list):
        raise ValueError("Invalid generated-example ownership manifest; no cleanup performed")
    retained_names = {}
    for name in artifacts:
        if not owned_name(name):
            continue
        key = name.casefold()
        if key in retained_names:
            raise ValueError("Generated example paths collide by case; no cleanup performed")
        retained_names[key] = name
    stale, seen = [], set()
    for row in manifest["files"]:
        name, expected = row.get("path"), row.get("sha256")
        if not isinstance(name, str) or not owned_name(name) or name == OWNERSHIP or name in seen or not isinstance(expected, str) or not re.fullmatch(r"[0-9a-f]{64}", expected):
            raise ValueError("Unsafe generated-example ownership record; no cleanup performed")
        seen.add(name)
        path = destination(output, name)
        if name not in artifacts and path.exists():
            if not path.is_file() or sha256(path.read_bytes()) != expected:
                raise ValueError(f"Stale example output has local edits; refusing to delete it: {name}")
            replacement = retained_names.get(name.casefold())
            if replacement is not None:
                retained = destination(output, replacement)
                # Windows can resolve both spellings to the same owned file.
                # It is retained output, not obsolete data to unlink before
                # writing the new index. On case-sensitive filesystems the
                # distinct old file still follows the normal checked cleanup.
                if retained.exists() and path.samefile(retained):
                    continue
            stale.append(path)
    return stale
